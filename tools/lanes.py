"""Writes dispatch/lanes.py: the median typical fee of each lane, from the price requests of saved weeks.

    python -m tools.lanes final-fresh skeptic-base-s14 simple-main-s14 orch-head-record

A request's typical fee is its lane's cost to a driver times a noise of its own (HANDBOOK.md, "The typical fee"); the median over many weeks drops the noise."""
from __future__ import annotations

import math
import os
import statistics
import sys
import textwrap
from collections import defaultdict

from tools.study import runs

FEWEST = 8  # requests: a lane seen less often keeps each request's own number


def main() -> None:
    tags, fees, seen = sys.argv[1:], defaultdict(list), set()
    for tag in tags:
        for run in runs(tag):
            if run["seed"] in seen:  # a seed's requests are the same in every run of it
                continue
            seen.add(run["seed"])
            for event in run["events"]:
                if event["kind"] == "price_request" and len(event["request"]["legs"]) == 1:
                    leg = event["request"]["legs"][0]
                    fees[f"{leg['pickup']['placeId']}>{leg['delivery']['placeId']}"].append(event["request"]["referenceFeeCents"])
    lanes = {lane: int(statistics.median(cents)) for lane, cents in sorted(fees.items()) if len(cents) >= FEWEST}
    noise = [math.log(c / lanes[lane]) for lane, cents in fees.items() if lane in lanes for c in cents]
    print(f"{len(seen)} weeks, {len(noise)} requests on {len(lanes)} lanes; log(typical fee / lane median): sd {statistics.pstdev(noise):.3f}")
    with open(os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "dispatch", "lanes.py"), "w") as file:
        file.write(f'"""The median typical fee of each lane, in cents. Generated by `python -m tools.lanes {" ".join(tags)}`: do not edit."""\n')
        table = ", ".join(f"{lane!r}: {cents}" for lane, cents in lanes.items())
        file.write("LANES = {\n" + textwrap.fill(table, 200, initial_indent="    ", subsequent_indent="    ") + ",\n}\n")


if __name__ == "__main__":
    main()
